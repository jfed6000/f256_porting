#!/usr/bin/env python3
"""mkassets.py - the starter's art, drawn in code: a palette, a few 16x16 tiles, a 64x15 tile map, one 32x32 sprite.

Writes assets/*.bin and src/assets.d (the equates the program assembles against: the converter owns every number,
so change the art here and the program follows, or fails to assemble). Replace this with your own converter: the
formats are below, and they're what VICKY reads.

    clut.bin    256 entries x 4 bytes, B, G, R, A (entry 0 is transparent in sprites and tile maps)
    tiles.bin   16x16 tiles, 256 bytes each, one byte a pixel, one tile after another (a linear tile set)
                tile 0 is left empty: MAME skips tile number 0
    map.bin     MAP.W x MAP.H entries, 2 bytes each: the tile number, then an attribute byte
                (bits 2:0 the tile set, bits 5:3 the CLUT)
    sprite.bin  one 32x32 sprite cell, 1,024 bytes, one byte a pixel
"""
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
OUT = HERE / 'assets'
OUT.mkdir(exist_ok=True)

# ---- the palette (index: (r, g, b)); everything uses CLUT 0
PAL = {1: (31, 15, 7), 2: (70, 120, 200), 3: (110, 160, 230), 4: (240, 240, 250), 5: (60, 150, 60),
       6: (35, 95, 40), 7: (150, 70, 45), 8: (190, 110, 70), 9: (90, 60, 40), 10: (255, 211, 74), 11: (255, 157, 60)}
clut = bytearray(1024)
for i, (r, g, b) in PAL.items():
    clut[i * 4:i * 4 + 4] = bytes([b, g, r, 255])

# ---- tiles
def tile(fn):
    return bytes(fn(x, y) for y in range(16) for x in range(16))

TILES = [
    tile(lambda x, y: 0),                                                   # 0 empty (MAME skips it)
    tile(lambda x, y: 2),                                                   # 1 sky, high
    tile(lambda x, y: 4 if (x - 7.5) ** 2 / 2.2 + (y - 8.5) ** 2 < 22 else 2),   # 2 a puff of cloud on the high sky
    tile(lambda x, y: 6 if y < 3 else (5 if y < 6 else 9)),                 # 3 grass on dirt
    tile(lambda x, y: 9 if (x * 7 + y * 3) % 11 else 1),                    # 4 dirt
    tile(lambda x, y: 1 if y % 8 == 7 or (x + (8 if y // 8 else 0)) % 16 == 15 else (8 if y % 8 < 2 else 7)),  # 5 brick
    tile(lambda x, y: 3),                                                   # 6 sky, low
]
tiles = b''.join(TILES)

# ---- the map: sky, clouds here and there, a brick wall now and then, grass, dirt
W, H = 64, 15
rows = []
for y in range(H):
    row = []
    for x in range(W):
        if y < 11:
            t = 1 if y < 6 else 6
            if (y == 2 and x % 13 in (2, 3, 4)) or (y == 4 and x % 17 in (8, 9)):
                t = 2
            if y >= 8 and x % 16 in (9, 10):                             # a wall to show the scroll
                t = 5
        elif y == 11:
            t = 3
        else:
            t = 4
        row += [t, 0]                                                     # tile set 0, CLUT 0
    rows.append(bytes(row))
mapb = b''.join(rows)

# ---- the sprite: a ball with an outline and a highlight
def spr(x, y):
    d = (x - 15.5) ** 2 + (y - 15.5) ** 2
    if d > 15 ** 2:
        return 0
    if d > 13 ** 2:
        return 1
    return 4 if (x - 11) ** 2 + (y - 10) ** 2 < 10 else (10 if d < 9 ** 2 else 11)
sprite = bytes(spr(x, y) for y in range(32) for x in range(32))

for name, data in (('clut.bin', clut), ('tiles.bin', tiles), ('map.bin', mapb), ('sprite.bin', sprite)):
    (OUT / name).write_bytes(data)

(HERE / 'src' / 'assets.d').write_text(f"""* assets.d: GENERATED by tools/mkassets.py. Do not edit; change the converter and rebuild.
TIL.Size            equ       {len(tiles)}               tiles.bin
MAP.W               equ       {W}                  the map, in tiles
MAP.H               equ       {H}
MAP.Size            equ       {len(mapb)}               map.bin
SPR.Size            equ       {len(sprite)}               sprite.bin
""")
print(f'assets: {len(TILES)} tiles, a {W}x{H} map, one sprite, {len(PAL)} colours')
